// ShellSessionListHandler returns an http.Handler that lists active shell
// sessions for the authenticated user. Admin users see all sessions.
func (h *Handler) ShellSessionListHandler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet {
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		sessInfo := UserSessionFromContext(r)
		if sessInfo == nil {
			http.Error(w, "Unauthorized: user session required", http.StatusUnauthorized)
			return
		}

		type sessionInfo struct {
			ID            string `json:"id"`
			AgentID       string `json:"agent_id"`
			CreatedAt     string `json:"created_at"`
			Attached      bool   `json:"attached"`
			BufferedBytes int    `json:"buffered_bytes"`
		}

		sessions := []sessionInfo{}
		h.shellSessions.Range(func(ss *ShellSession) bool {
			// Non-admin users only see their own sessions.
			if !isAdmin(sessInfo) && ss.UserID() != sessInfo.UserID {
				return true
			}
			sessions = append(sessions, sessionInfo{
				ID:            ss.ID(),
				AgentID:       ss.AgentID(),
				CreatedAt:     ss.CreatedAt().Format("2006-01-02T15:04:05Z07:00"),
				Attached:      ss.Attached(),
				BufferedBytes: ss.BufferedBytes(),
			})
			return true
		})

		// Sort by agent_id, then by session ID for same agent.
		sort.Slice(sessions, func(i, j int) bool {
			if sessions[i].AgentID != sessions[j].AgentID {
				return sessions[i].AgentID < sessions[j].AgentID
			}
			return sessions[i].ID < sessions[j].ID
		})

		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(sessions)
	})
}

// ShellSessionDeleteHandler returns an http.Handler that explicitly
// terminates a persistent shell session. User-scoped: non-admin users
// can only delete their own sessions.
func (h *Handler) ShellSessionDeleteHandler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodDelete && r.Method != http.MethodPost {
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		sessInfo := UserSessionFromContext(r)
		if sessInfo == nil {
			http.Error(w, "Unauthorized: user session required", http.StatusUnauthorized)
			return
		}

		var req struct {
			ID string `json:"id"`
		}
		if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1024)).Decode(&req); err != nil {
			http.Error(w, "bad request body", http.StatusBadRequest)
			return
		}
		if req.ID == "" {
			http.Error(w, "missing id", http.StatusBadRequest)
			return
		}

		ss := h.shellSessions.Load(req.ID)
		if ss == nil || ss.IsDead() {
			http.Error(w, "shell session not found", http.StatusNotFound)
			return
		}

		// Verify ownership.
		if !isAdmin(sessInfo) && ss.UserID() != sessInfo.UserID {
			http.Error(w, "access denied", http.StatusForbidden)
			return
		}

		h.shellSessions.Delete(req.ID)
		ss.Close()
		log.Printf("shell: deleted session %s (agent=%s)", req.ID, ss.AgentID())
		w.WriteHeader(http.StatusNoContent)
	})
}

// isAdmin reports whether the user session has admin role.
func isAdmin(sessInfo *auth.UserSessionInfo) bool {
	return sessInfo != nil && auth.HasPermission(sessInfo.Role, auth.PermAdmin)
}

// agentOwnedByUser checks if any session with the given agentID belongs
// to the specified user.
func (h *Handler) agentOwnedByUser(agentID string, userID int64) bool {
	found := false
	h.reg.Range(func(s *Session) bool {
		if s.AgentID() == agentID && s.UserID() == userID {
			found = true
			return false
		}
		return true
	})
	return found
}
